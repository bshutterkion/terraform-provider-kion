func testAccCustomVariableConfigBasic(rName string) string {
	return fmt.Sprintf(`
resource "kion_custom_variable" "test" {
  name                 = %[1]q
  description          = "test-acc custom variable"
  type                 = "string"
  default_value_string = "test-acc-default"
  owner_user_ids       = [1]
}
`, rName)
}

